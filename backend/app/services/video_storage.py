"""Uploaded lesson videos on disk.

- Uploads are streamed chunk by chunk into a temporary ``.part`` file inside
  the storage directory (same filesystem, so committing is an atomic rename)
  and never held in memory.
- The size limit is enforced while streaming; failed or interrupted uploads
  remove their temporary file.
- The type is detected from the file's first bytes (MP4/WebM/Ogg), never
  from the client's filename or Content-Type.
- Stored names are generated by the server (``<asset id>.<ext>``) and checked
  again before any filesystem access, so paths cannot be traversed.
- Files are only ever served through the authorized streaming endpoint.
"""

import asyncio
import logging
import os
import re
import time
import unicodedata
import uuid
from collections.abc import AsyncIterator
from pathlib import Path
from urllib.parse import unquote

from app.core.config import settings

logger = logging.getLogger(__name__)

CHUNK_BYTES = 1024 * 1024
SNIFF_BYTES = 64
INCOMING_DIRECTORY = ".incoming"
STALE_UPLOAD_SECONDS = 6 * 3600
_STORAGE_NAME = re.compile(r"^[0-9a-f]{24}\.(mp4|webm|ogv)$")


class VideoUploadError(Exception):
    """Base class; ``str(error)`` is safe to show to users."""


class UploadTooLargeError(VideoUploadError):
    pass


class UnsupportedVideoError(VideoUploadError):
    pass


class RangeNotSatisfiableError(Exception):
    pass


def detect_video_type(head: bytes) -> tuple[str, str] | None:
    """(content type, extension) from the first bytes, or None if unsupported."""
    if len(head) >= 12 and head[4:8] == b"ftyp":
        if head[8:12] == b"qt  ":
            return None  # QuickTime .mov: often not playable in browsers
        return "video/mp4", "mp4"
    if head[:4] == b"\x1a\x45\xdf\xa3":
        # EBML: only the WebM doctype (Matroska .mkv is not browser-playable).
        return ("video/webm", "webm") if b"webm" in head[:SNIFF_BYTES] else None
    if head[:4] == b"OggS":
        return "video/ogg", "ogv"
    return None


def sanitize_filename(name: str | None) -> str:
    """Display-only version of the client's filename (never used for storage)."""
    if not name:
        return "video"
    name = unquote(name)
    name = name.replace("\\", "/").rsplit("/", 1)[-1]
    name = "".join(char for char in unicodedata.normalize("NFC", name) if unicodedata.category(char)[0] != "C")
    name = name.strip(" .")[:120]
    return name or "video"


def storage_directory() -> Path:
    directory = settings.video_storage_dir
    (directory / INCOMING_DIRECTORY).mkdir(parents=True, exist_ok=True)
    return directory


def storage_path(storage_name: str) -> Path:
    if not _STORAGE_NAME.fullmatch(storage_name or ""):
        raise ValueError("Invalid storage name.")
    directory = storage_directory().resolve()
    path = (directory / storage_name).resolve()
    if path.parent != directory:
        raise ValueError("Invalid storage name.")
    return path


def cleanup_stale_uploads(max_age_seconds: int = STALE_UPLOAD_SECONDS) -> int:
    """Removes leftovers of uploads interrupted by a crash or restart."""
    incoming = storage_directory() / INCOMING_DIRECTORY
    removed = 0
    cutoff = time.time() - max_age_seconds
    for path in incoming.glob("*.part"):
        try:
            if path.stat().st_mtime < cutoff:
                path.unlink()
                removed += 1
        except OSError:
            continue
    return removed


class ReceivedUpload:
    def __init__(self, temp_path: Path, size_bytes: int, content_type: str, extension: str) -> None:
        self.temp_path = temp_path
        self.size_bytes = size_bytes
        self.content_type = content_type
        self.extension = extension

    def discard(self) -> None:
        self.temp_path.unlink(missing_ok=True)


async def receive_upload(chunks: AsyncIterator[bytes], max_bytes: int) -> ReceivedUpload:
    """Streams the request body to a temporary file and validates it."""
    temp_path = storage_directory() / INCOMING_DIRECTORY / f"{uuid.uuid4().hex}.part"
    size = 0
    head = b""
    handle = await asyncio.to_thread(open, temp_path, "wb")
    try:
        async for chunk in chunks:
            if not chunk:
                continue
            size += len(chunk)
            if size > max_bytes:
                raise UploadTooLargeError("The video is larger than the allowed upload size.")
            if len(head) < SNIFF_BYTES:
                head += chunk[: SNIFF_BYTES - len(head)]
            await asyncio.to_thread(handle.write, chunk)
        await asyncio.to_thread(handle.close)
        if size == 0:
            raise UnsupportedVideoError("The uploaded file is empty.")
        detected = detect_video_type(head)
        if detected is None:
            raise UnsupportedVideoError("Unsupported video format. Upload an MP4 or WebM file.")
    except BaseException:
        # Includes client disconnects and cancellation: never leave partial files.
        handle.close()
        temp_path.unlink(missing_ok=True)
        raise
    return ReceivedUpload(temp_path, size, *detected)


def commit_upload(upload: ReceivedUpload, asset_id: str) -> str:
    storage_name = f"{asset_id}.{upload.extension}"
    os.replace(upload.temp_path, storage_path(storage_name))
    return storage_name


def delete_stored_file(storage_name: str) -> None:
    try:
        storage_path(storage_name).unlink(missing_ok=True)
    except (OSError, ValueError):
        logger.warning("A stored video file could not be removed.")


def parse_range(header: str | None, size: int) -> tuple[int, int] | None:
    """Single byte range -> inclusive (start, end); None = whole file."""
    if not header:
        return None
    match = re.fullmatch(r"\s*bytes=(\d*)-(\d*)\s*", header)
    if not match or (not match.group(1) and not match.group(2)):
        raise RangeNotSatisfiableError
    first, last = match.groups()
    if first:
        start = int(first)
        end = int(last) if last else size - 1
    else:  # suffix range: the last N bytes
        length = int(last)
        if length == 0:
            raise RangeNotSatisfiableError
        start = max(size - length, 0)
        end = size - 1
    end = min(end, size - 1)
    if start >= size or start > end:
        raise RangeNotSatisfiableError
    return start, end


async def iter_file(path: Path, start: int, end: int) -> AsyncIterator[bytes]:
    handle = await asyncio.to_thread(open, path, "rb")
    try:
        await asyncio.to_thread(handle.seek, start)
        remaining = end - start + 1
        while remaining > 0:
            chunk = await asyncio.to_thread(handle.read, min(CHUNK_BYTES, remaining))
            if not chunk:
                break
            remaining -= len(chunk)
            yield chunk
    finally:
        await asyncio.to_thread(handle.close)
