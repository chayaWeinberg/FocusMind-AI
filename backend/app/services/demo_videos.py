"""Install the locally generated demonstration videos ("סרטון הדגמה") into the
catalog lessons, through the regular video storage (type sniffing, atomic
files, authorized streaming).

Generated by frontend/scripts/demo-videos/generate.mjs (offline, in Edge).
The MP4 files are not in Git; the generator and this installer are.

Rules (idempotent, never destructive):
- only seeded catalog lessons (course slug + seed_key from the manifest);
- a lesson is changed only if it has no video, or an external link set by
  the catalog video tool (catalog_video_key), or an older demo video;
  uploads by people, links chosen by people and videos removed by a content
  manager (cleared_by_manager) are never touched;
- the curated external link (e.g. the CS50 lecture page) is kept as the
  lesson's ``reference``;
- an identical file (same demo key and sha256) is never stored twice;
  restarting Docker installs nothing;
- users, enrollments and progress are not modified.
"""

import hashlib
import json
from collections.abc import AsyncIterator
from dataclasses import dataclass
from pathlib import Path

from bson import ObjectId
from pymongo.asynchronous.database import AsyncDatabase

from app.core.config import settings
from app.services import video_storage
from app.services.courses import utcnow

# Owner of the demo assets: not a user account (no quota, no personal data).
DEMO_OWNER_ID = ObjectId("000000000000000000d3a0de")
CHUNK = 1024 * 1024


@dataclass
class DemoOutcome:
    course_slug: str
    seed_key: str
    action: str  # installed | unchanged | skipped
    detail: str


def demo_key(entry: dict) -> str:
    return f"demo:{entry['course']}:{entry['key']}:v{entry['version']}"


async def _file_chunks(path: Path) -> AsyncIterator[bytes]:
    with path.open("rb") as handle:
        while chunk := handle.read(CHUNK):
            yield chunk


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(CHUNK), b""):
            digest.update(chunk)
    return digest.hexdigest()


async def _asset_for(database: AsyncDatabase, entry: dict, path: Path, sha256: str) -> tuple[ObjectId, bool]:
    """Reuses a stored identical asset, otherwise stores the file. Returns (id, created)."""
    key = demo_key(entry)
    existing = await database.video_assets.find_one({"demo_key": key, "sha256": sha256})
    if existing:
        try:
            if video_storage.storage_path(existing["storage_name"]).is_file():
                return existing["_id"], False
        except ValueError:
            pass
        await database.video_assets.delete_one({"_id": existing["_id"]})  # file lost: store again
    upload = await video_storage.receive_upload(_file_chunks(path), settings.max_video_upload_bytes)
    asset_id = ObjectId()
    storage_name = video_storage.commit_upload(upload, str(asset_id))
    try:
        await database.video_assets.insert_one({
            "_id": asset_id,
            "owner_id": DEMO_OWNER_ID,
            "storage_name": storage_name,
            "content_type": upload.content_type,
            "size_bytes": upload.size_bytes,
            "original_name": f"סרטון הדגמה - {entry['title']}.mp4",
            "created_at": utcnow(),
            "demo_key": key,
            "sha256": sha256,
        })
    except Exception:
        video_storage.delete_stored_file(storage_name)
        raise
    return asset_id, True


async def _release_old_demo(database: AsyncDatabase, asset_id: ObjectId) -> None:
    if await database.lessons.count_documents({"video.asset_id": asset_id}):
        return
    asset = await database.video_assets.find_one({"_id": asset_id, "owner_id": DEMO_OWNER_ID})
    if asset:
        await database.video_assets.delete_one({"_id": asset_id})
        video_storage.delete_stored_file(asset["storage_name"])


def load_manifest(directory: Path) -> list[dict]:
    manifest = json.loads((directory / "manifest.json").read_text(encoding="utf-8"))
    return manifest["videos"]


async def install_demo_videos(database: AsyncDatabase, directory: Path, dry_run: bool = False) -> list[DemoOutcome]:
    await database.video_assets.create_index(
        [("demo_key", 1), ("sha256", 1)], partialFilterExpression={"demo_key": {"$type": "string"}}
    )
    outcomes: list[DemoOutcome] = []
    for entry in load_manifest(directory):
        slug, seed_key = entry["course"], entry["key"]
        course = await database.courses.find_one({"type": "catalog", "slug": slug})
        lesson = await database.lessons.find_one({"course_id": course["_id"], "seed_key": seed_key}) if course else None
        if lesson is None:
            outcomes.append(DemoOutcome(slug, seed_key, "skipped", "lesson not found"))
            continue
        path = directory / entry["file"]
        if not path.is_file():
            outcomes.append(DemoOutcome(slug, seed_key, "skipped", f"missing file {entry['file']}"))
            continue
        video = lesson.get("video") or {"source_type": "none"}
        source = video.get("source_type", "none")
        key = demo_key(entry)
        if video.get("cleared_by_manager"):
            outcomes.append(DemoOutcome(slug, seed_key, "skipped", "a content manager removed the video"))
            continue
        is_demo = source == "upload" and bool(video.get("demo_key"))
        if source == "upload" and not is_demo:
            outcomes.append(DemoOutcome(slug, seed_key, "skipped", "keeps its uploaded video"))
            continue
        if source == "external" and not video.get("catalog_video_key"):
            outcomes.append(DemoOutcome(slug, seed_key, "skipped", "keeps a link chosen by a person"))
            continue
        sha256 = _sha256(path)
        if is_demo and video.get("demo_key") == key and video.get("sha256") == sha256:
            outcomes.append(DemoOutcome(slug, seed_key, "unchanged", key))
            continue
        if dry_run:
            outcomes.append(DemoOutcome(slug, seed_key, "would install", key))
            continue

        asset_id, created = await _asset_for(database, entry, path, sha256)
        changes: dict = {
            "video": {"source_type": "upload", "asset_id": asset_id, "demo_key": key, "sha256": sha256},
            "duration_seconds": entry.get("durationSeconds"),
            "updated_at": utcnow(),
        }
        if source == "external" and video.get("source"):
            attribution = video["source"]
            changes["reference"] = {
                "name": attribution.get("name"),
                "url": attribution.get("page_url") or video.get("url"),
                "license": attribution.get("license"),
            }
        await database.lessons.update_one({"_id": lesson["_id"]}, {"$set": changes})
        if is_demo and video.get("asset_id") != asset_id:
            await _release_old_demo(database, video["asset_id"])
        outcomes.append(DemoOutcome(slug, seed_key, "installed", f"{key} ({'new file' if created else 'existing file'})"))
    return outcomes
