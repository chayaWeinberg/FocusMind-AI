"""MongoDB document shapes for courses, lessons, enrollments, progress,
video assets and learning sessions. All IDs are ObjectIds; all timestamps are
timezone-aware UTC datetimes."""

from datetime import datetime
from typing import Literal, NotRequired, TypedDict

from bson import ObjectId

CourseType = Literal["catalog", "personal"]
CourseStatus = Literal["published", "draft"]
VideoSourceType = Literal["none", "upload", "external"]
ExternalProvider = Literal["direct", "youtube", "page"]
AttentionState = Literal["ON_SCREEN", "OFF_SCREEN", "FACE_ABSENT", "UNCERTAIN", "NOT_MEASURED"]


class CourseDocument(TypedDict):
    _id: NotRequired[ObjectId]
    title: str
    description: str
    category: str
    type: CourseType
    owner_id: ObjectId | None  # set only for personal courses
    status: CourseStatus
    slug: NotRequired[str]  # stable key of seeded catalog courses
    difficulty: NotRequired[str]  # beginner | intermediate | advanced
    academy: NotRequired[bool]  # FocusMind Academy: full lessons that play here
    external_library: NotRequired[bool]  # lessons link to lectures on their own sites
    retired: NotRequired[bool]  # retired demonstration course: hidden everywhere, data kept
    created_at: datetime
    updated_at: datetime


class LessonVideo(TypedDict):
    source_type: VideoSourceType
    asset_id: NotRequired[ObjectId]  # source_type == "upload"
    url: NotRequired[str]  # source_type == "external"
    provider: NotRequired[ExternalProvider]
    embed_id: NotRequired[str]  # provider == "youtube"
    # Attribution of curated catalog videos: {"name", "page_url", "license"}.
    source: NotRequired[dict]
    # Set only by `python -m app.catalog_videos apply`; a video without it was
    # chosen by a person and is never replaced by the tool.
    catalog_video_key: NotRequired[str]
    # A content manager removed the video on purpose: the tool leaves it empty.
    cleared_by_manager: NotRequired[bool]
    # Installed by `python -m app.demo_videos` (original demonstration video).
    demo_key: NotRequired[str]
    sha256: NotRequired[str]


class LessonDocument(TypedDict):
    _id: NotRequired[ObjectId]
    course_id: ObjectId
    title: str
    description: str
    order: int
    video: LessonVideo
    duration_seconds: float | None
    # Optional external resource kept next to a demo video: {"name", "url", "license"}.
    reference: NotRequired[dict]
    # Catalog library: the real video behind the lesson and its verification.
    resource: NotRequired[dict]
    seed_key: NotRequired[str]
    created_at: datetime
    updated_at: datetime


class EnrollmentDocument(TypedDict):
    _id: NotRequired[ObjectId]
    user_id: ObjectId
    course_id: ObjectId
    enrolled_at: datetime


class LessonProgressDocument(TypedDict):
    _id: NotRequired[ObjectId]
    user_id: ObjectId
    lesson_id: ObjectId
    course_id: ObjectId
    position_seconds: float
    duration_seconds: float | None
    completed: bool
    completed_at: datetime | None
    updated_at: datetime


class VideoAssetDocument(TypedDict):
    _id: NotRequired[ObjectId]
    owner_id: ObjectId
    storage_name: str  # "<asset id>.<ext>", generated by the server
    content_type: str  # detected from the file content, not the client
    size_bytes: int
    original_name: str  # sanitized, display only
    created_at: datetime


class LearningSessionDocument(TypedDict):
    _id: NotRequired[ObjectId]
    user_id: ObjectId
    course_id: ObjectId
    lesson_id: ObjectId
    started_at: datetime
    ended_at: datetime | None
    active_ms: int  # time the video actually played (Smart Timer), never paused/buffering time
    break_ms: NotRequired[int]  # breaks taken from the Smart Timer
    segment_count: int
    trackable: NotRequired[bool]  # False for YouTube: time only, no attention segments
    last_seen_at: NotRequired[datetime]  # last heartbeat; no end + old heartbeat = interrupted


class AttentionSegmentDocument(TypedDict):
    """One stretch of playback with a single attention state (ReplayAI input).

    Video time (video_start/video_end, seconds in the media) and session time
    (session_start_ms/session_end_ms, since the session started) are stored
    separately: they diverge with pauses, seeking, replays and playback rate.
    """

    _id: NotRequired[ObjectId]
    session_id: ObjectId
    user_id: ObjectId
    course_id: ObjectId
    lesson_id: ObjectId
    seq: int
    session_start_ms: int
    session_end_ms: int
    video_start: float
    video_end: float
    playback_rate: float
    state: AttentionState
    duration_ms: int
    concentration: int | None
    created_at: datetime
